window.MSI18N = (function () {
  "use strict";

  var dict = window.__MS_I18N__;
  var SUPPORTED = ["zh", "zh-TW", "en", "ja", "ru"];
  var NEXT_LABEL = { "zh": "繁體", "zh-TW": "EN", "en": "日本語", "ja": "Русский", "ru": "中文" };

  function normalize(value) {
    value = (value || "").toLowerCase();
    if (value.indexOf("zh") === 0) {
      return (value.indexOf("tw") >= 0 || value.indexOf("hk") >= 0 ||
              value.indexOf("hant") >= 0) ? "zh-TW" : "zh";
    }
    if (value.indexOf("ja") === 0) return "ja";
    if (value.indexOf("ru") === 0) return "ru";
    if (value.indexOf("en") === 0) return "en";
    return "";
  }

  function lang() {
    var query = normalize(new URLSearchParams(location.search).get("lang"));
    if (query) return query;
    try {
      var own = normalize(localStorage.getItem("ms_lang"));
      if (own) return own;
      var host = normalize(localStorage.getItem("ep_lang"));
      if (host) return host;
    } catch (e) { /* localStorage 不可用时走浏览器语言 */ }
    return normalize(navigator.language) || "en";
  }

  function t(key, fallback) {
    var table = dict[lang()] || {};
    return table[key] || (dict.en || {})[key] || (dict.zh || {})[key] || fallback || key;
  }

  function tf(key, fallback, vars) {
    var text = t(key, fallback);
    var values = vars || {};
    for (var name in values) text = text.split("{" + name + "}").join(values[name]);
    return text;
  }

  function apply() {
    document.querySelectorAll("[data-i18n]").forEach(function (node) {
      node.textContent = t(node.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (node) {
      node.placeholder = t(node.dataset.i18nPlaceholder);
    });
    document.querySelectorAll("[data-i18n-title]").forEach(function (node) {
      node.title = t(node.dataset.i18nTitle);
    });
  }

  function next() {
    return SUPPORTED[(SUPPORTED.indexOf(lang()) + 1) % SUPPORTED.length];
  }

  return { lang: lang, t: t, tf: tf, apply: apply, next: next, nextLabel: function () {
    return NEXT_LABEL[next()];
  } };
})();
